def _make_uuid_decode_value_callback(value: int) -> PalaceBrainfuckForeignFunction:
    def _cb(vm: PalaceBrainfuckVM) -> None:
        base = vm.pointer - 3
        vm.tape[base + _UUID_DECODE_VALUE_OFFSET] = value
        vm.tape[base + 4] = 0

    return _cb


def _uuid_invalid_base64_char_callback(vm: PalaceBrainfuckVM) -> None:
    raise InvalidBase64Character("Invalid character in url-safe base64 string")


