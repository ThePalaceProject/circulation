def uuid_bytes_to_urlsafe_b64(data: bytes) -> str:
    """Encode exactly 16 bytes as url-safe base64, including ``=`` padding
    (matching the shape of :func:`base64.urlsafe_b64encode`'s own output).

    :param data: Exactly 16 bytes, e.g. ``uuid.UUID.bytes``.
    """
    output = run_palace_brainfuck(
        UUID_ENCODE_BF,
        data,
        functions={"+": _uuid_lookup_encode_char_callback},
    )
    return output.decode()


