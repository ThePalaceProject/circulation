def _make_uuid_encode_char_callback(char_value: int) -> PalaceBrainfuckForeignFunction:
    def _cb(vm: PalaceBrainfuckVM) -> None:
        vm.tape[vm.pointer - 3] = char_value

    return _cb


_UUID_ENCODE_FUNCTIONS: Final[frozendict[str, PalaceBrainfuckForeignFunction]] = (
    frozendict(
        {
            str(v): _make_uuid_encode_char_callback(ord(ch))
            for v, ch in enumerate(_URLSAFE_BASE64_ALPHABET)
        }
    )
)


def _uuid_lookup_encode_char_callback(vm: PalaceBrainfuckVM) -> None:
    value = vm.tape[vm.pointer]
    output = run_palace_brainfuck(
        UUID_ENCODE_CHAR_BF, bytes([value]), functions=_UUID_ENCODE_FUNCTIONS
    )
    vm.tape[vm.pointer] = output[0]


