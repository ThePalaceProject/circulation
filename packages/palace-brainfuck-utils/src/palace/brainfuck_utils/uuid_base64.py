def urlsafe_b64_to_uuid_bytes(padded: str) -> bytes:
    """Decode a padded url-safe base64 string (24 characters: 22 meaningful
    plus ``==``) back into the original 16 bytes.

    :param padded: A 24-character url-safe base64 string, as produced by
        :func:`uuid_bytes_to_urlsafe_b64`.
    :raise InvalidBase64Character: If a character outside the url-safe
        base64 alphabet is encountered.
    """
    return run_palace_brainfuck(
        UUID_DECODE_BF,
        padded.encode(),
        functions={"-": _uuid_lookup_decode_value_callback},
    )
